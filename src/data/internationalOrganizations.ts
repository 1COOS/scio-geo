const affiliationCatalogWithReferencesSchema =
  internationalAffiliationCatalogSchema.superRefine((affiliations, context) => {
    const globalMembershipLimit = Math.floor(countriesByCode.size / 2)

    for (const [affiliationIndex, affiliation] of affiliations.entries()) {
      for (const [sourceIndex, sourceId] of affiliation.sourceIds.entries()) {
        if (!countrySourcesById.has(sourceId)) {
          context.addIssue({
            code: 'custom',
            message: `Unknown source ${sourceId} on ${affiliation.id}`,
            path: [affiliationIndex, 'sourceIds', sourceIndex],
          })
        }
      }

      for (const [
        countryIndex,
        countryCode,
      ] of affiliation.memberCountryCodes.entries()) {
        if (!countriesByCode.has(countryCode)) {
          context.addIssue({
            code: 'custom',
            message: `Unknown member country ${countryCode} on ${affiliation.id}`,
            path: [affiliationIndex, 'memberCountryCodes', countryIndex],
          })
        }
      }

      if (
        affiliation.category === 'global' &&
        affiliation.memberCountryCodes.length > globalMembershipLimit
      ) {
        context.addIssue({
          code: 'custom',
          message: `Global affiliation ${affiliation.id} covers more than half of the country catalogue`,
          path: [affiliationIndex, 'memberCountryCodes'],
        })
      }
    }
  })

export const internationalAffiliations =
  affiliationCatalogWithReferencesSchema.parse(internationalAffiliationContent)

const internationalAffiliationsByCountryCode = new Map<
  string,
  InternationalAffiliation[]
>()

for (const affiliation of internationalAffiliations) {
  for (const countryCode of affiliation.memberCountryCodes) {
    const countryAffiliations =
      internationalAffiliationsByCountryCode.get(countryCode) ?? []
    countryAffiliations.push(affiliation)
    internationalAffiliationsByCountryCode.set(countryCode, countryAffiliations)
  }
}

export function getInternationalAffiliationsForCountry(countryCode: string) {
  return internationalAffiliationsByCountryCode.get(countryCode) ?? []
}
